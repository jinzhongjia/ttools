func TestStagedDiffAndCommit(t *testing.T) {
	dir := t.TempDir()
	repo, err := gogit.PlainInit(dir, false)
	if err != nil {
		t.Fatal(err)
	}
	setUserConfig(t, repo, "Test", "test@example.com")
	wt, err := repo.Worktree()
	if err != nil {
		t.Fatal(err)
	}

	writeFile(t, dir, "hello.txt", "hello\n")
	if _, err := wt.Add("hello.txt"); err != nil {
		t.Fatal(err)
	}
	if _, err := wt.Commit("initial", &gogit.CommitOptions{Author: &object.Signature{Name: "Test", Email: "test@example.com"}}); err != nil {
		t.Fatal(err)
	}

	writeFile(t, dir, "hello.txt", "hello\nworld\n")
	if _, err := wt.Add("hello.txt"); err != nil {
		t.Fatal(err)
	}

	opened, err := OpenRepository(dir)
	if err != nil {
		t.Fatal(err)
	}
	has, err := HasStagedChanges(opened)
	if err != nil {
		t.Fatal(err)
	}
	if !has {
		t.Fatal("expected staged changes")
	}

	diffs, err := GetStagedDiffs(opened)
	if err != nil {
		t.Fatal(err)
	}
	if len(diffs) != 1 || diffs[0].Path != "hello.txt" || !strings.Contains(diffs[0].Patch, "+world") {
		t.Fatalf("bad diffs: %+v", diffs)
	}

	hash, err := Commit(opened, "feat: update hello")
	if err != nil {
		t.Fatal(err)
	}
	if hash.IsZero() {
		t.Fatal("zero hash")
	}
}

